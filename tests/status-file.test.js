test("STATUS.md leaks no internal details or approval claims", () => {
  const raw = fs.readFileSync(STATUS_PATH, "utf8");
  const normalized = normalize(raw);
  // فحوصُ البيانات الشخصيّة/التفاصيل الداخليّة تُطبَّق على نصَّين معاً (يكفي
  // أحدهما ليُبلَّغ خطأً)، لا نصٍّ واحدٍ:
  // ١) `sourceText` — النصّ الخامّ بعد فكّ مراجع HTML فقط، بلا لمس أيّ وسمٍ
  //    ولا سمةٍ ولا تعليقٍ: بيانٌ حسّاسٌ داخل قيمة سمةٍ (كـ`href="mailto:
  //    م@مثال.اختبار"` أو `href="tel:+49-..."`) أو داخل تعليق HTML (كـ
  //    `<!-- contact: user@example.com; api key: secret -->`) ينشره
  //    المصدرُ العامُّ فعليّاً على GitHub بصرف النظر عمّا يُعرَض للقارئ في
  //    الصفحة المُصيَّرة؛ إسقاطُ الوسم أو التعليق قبل هذا الفحص كان يُخفي
  //    كِلا الشكلَين عن EMAIL_RE/PHONE_RE/BANNED_SUBSTRINGS (ملاحظة Codex،
  //    جولتان: السمات ثمّ التعليقات). لا يُطبَّق هذا على CLAIM_PATTERNS
  //    عمداً: ادّعاءُ اعتمادٍ يُعَدّ ادّعاءً حين يُعرَض لقارئٍ فعليّاً، لا حين
  //    يبقى نصّاً خاملاً داخل تعليقٍ لا يُصيَّر إطلاقاً.
  // ٢) `strippedForPersonalData` — بعد حلّ روابط/صور Markdown، وإسقاط
  //    تشديدها، ووسم HTML المضمّن (stripTags() وحدها، لا stripInlineHtml()،
  //    فالتعليقات تبقى): رقمُ هاتفٍ بفواصل مُرمَّزةٍ كـ"+49&ensp;151&ensp;..."،
  //    أو مُشدَّدةٍ كـ"+49 **151** ..."، أو داخل رابطٍ كـ"+49 [151](#)
  //    23456789" (ملاحظة Codex الرابعة)، أو مقسومٍ بوسمٍ سطريٍّ كـ"+49
  //    <strong>151</strong> ..." — حتى لو وقع هذا كلُّه داخل تعليقٍ (كـ
  //    "<!-- +49 <strong>151</strong> ... -->" — ملاحظة Codex سابقة) — كلُّها
  //    تُعرَض رقماً عاديّاً واحداً فعليّاً أو منشورةٌ في المصدر العامّ على
  //    حالها، لكنّ الفاصلَ الحرفيَّ يمنع مطابقته في `sourceText` وحده.
  //    استخدامُ stripTags() لا stripInlineHtml() هنا مقصودٌ: الأخيرة تُسقط
  //    التعليقاتِ كاملةً (مناسبةٌ لإعادة بناء النصّ المعروض في normalize()،
  //    لا لفحصٍ يلزمه أن يرى محتوى التعليق نفسَه).
  const sourceText = decodeHtmlEntities(raw);
  const strippedForPersonalData = stripTags(resolveLinks(sourceText).replace(/[*_~`]/g, ""));
  function leaksSensitiveData(re) {
    return re.test(sourceText) || re.test(strippedForPersonalData);
  }

  assert.equal(leaksSensitiveData(EMAIL_RE), false, "STATUS.md must not contain an email address");
  assert.equal(leaksSensitiveData(PHONE_RE), false, "STATUS.md must not contain a phone number");
  assert.equal(
    leaksSensitiveData(HEX_ID_RE),
    false,
    "STATUS.md must not contain a long hex id (looks like a job/asset id)"
  );
  assert.equal(
    leaksSensitiveData(PREFIXED_ID_RE),
    false,
    "STATUS.md must not contain an asset_/job_ prefixed identifier"
  );

  // BANNED_SUBSTRINGS (مطابَقةٌ حرفيّةٌ بـ.includes() لا نمطاً) تُفحَص على
  // ثلاثة نصوصٍ: `normalized` (المعروض)، و`sourceTextLower` (الخامّ، يلتقط
  // ما يبقى حرفيّاً حتى بلا معالجةٍ)، و`strippedForPersonalData` مُصغَّرةً
  // (المحافظة على التعليقات، المطبَّعة الوسمَ): تفصيلٌ داخليٌّ داخل تعليقٍ
  // يقطعه وسمٌ (كـ"<!-- api <strong>key</strong>: secret -->") يُفلت
  // الفحصَين الأوّلَين معاً — `normalized` يُسقط التعليقَ كاملاً، وسورس
  // تكست الخامّ يُبقي الوسمَ قاطعاً — رغم نشر التفصيل فعليّاً في المصدر
  // العامّ (ملاحظة Codex).
  const sourceTextLower = sourceText.toLowerCase();
  const strippedForPersonalDataLower = strippedForPersonalData.toLowerCase();
  const offenders = [...BANNED_SUBSTRINGS, ...CLAIM_PATTERNS].filter((phrase) =>
    phrase instanceof RegExp
      ? phrase.test(normalized)
      : normalized.includes(phrase) ||
        sourceTextLower.includes(phrase) ||
        strippedForPersonalDataLower.includes(phrase)
  );
  assert.deepEqual(
    offenders,
    [],
    `STATUS.md contains banned content: ${offenders.join(", ")}`
  );
});
