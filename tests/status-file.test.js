// يفكّ مراجعَ محارف HTML (العدديّة والاسميّة الشائعة)، أسوةً بالدالّة نفسها
// في check-robots-and-indexing.js/check-no-approval-claims.js: عبارةٌ
// كـ"clinically&nbsp;approved" في Markdown تُعرَض "clinically approved"
// بمسافةٍ حقيقيّةٍ فعليّاً، لكنّ "&nbsp;" الحرفيّة نصٌّ عاديٌّ لا مسافةٌ
// بمعنى \s، فتُفلت أنماط CLAIM_PATTERNS من المطابقة ما لم تُفكَّ أوّلاً
// (ملاحظة Codex). المرجعُ العدديّ لا يلزمه ";" بمعيار HTML5. القائمةُ تشمل
// مراجعَ المسافة البيضاء الاسميّةَ الأخرى التي يفكّها العارضُ (لا "nbsp"
// وحدها): "&ensp;"/"&emsp;" وأخواتهما تُعرَض مسافاتٍ فعليّةً أيضاً، فتُفلت
// نفسَ إفلات "&nbsp;" لو اقتُصر عليها وحدها (ملاحظة Codex الثانية). ومراجعُ
// أخرى بحالة أحرفٍ مختلفةٍ (Tab وNewLine وMediumSpace وأخواتها) حسّاسةٌ
// لحالة الأحرف بمعيار HTML5 (لا صلةَ لها بـ"tab"/"newline" الصغيرتَين)،
// وكانت غائبةً كليّاً عن القائمة السابقة رغم كونها مسافاتٍ فعليّةً أيضاً
// (ملاحظة Codex الثالثة). هذه القائمةُ ليست الجدولَ الكاملَ لمراجع HTML5
// الاسميّة (يفوق ألفَي مدخلٍ)، بل كلُّ مرجعٍ منها يُعرَض مسافةً بيضاء
// فعليّاً — وهو ما يلزم هذا الحارسَ تحديداً.
const NAMED_ENTITIES = {
  amp: "&",
  lt: "<",
  gt: ">",
  quot: '"',
  apos: "'",
  nbsp: " ",
  NonBreakingSpace: " ",
  ensp: " ",
  emsp: " ",
  emsp13: " ",
  emsp14: " ",
  numsp: " ",
  puncsp: " ",
  thinsp: " ",
  ThinSpace: " ",
  hairsp: " ",
  VeryThinSpace: " ",
  MediumSpace: " ",
  Tab: " ",
  NewLine: " ",
};
function decodeHtmlEntities(text) {
  // [a-zA-Z][a-zA-Z0-9]*؛ لا [a-zA-Z]+ وحدها: مرجعٌ اسميٌّ بمعيار HTML5 قد
  // يحمل رقماً بعد الحرف الأوّل (كـ"emsp13"/"emsp14" أعلاه)، وكان النمطُ
  // السابق لا يقبل رقماً في اسم المرجع أصلاً، فيستحيل الوصولُ إلى هذين
  // المدخلَين في NAMED_ENTITIES مهما فُعِّلا فيها (كودٌ ميتٌ فعليّاً — ملاحظة
  // Codex).
  return text.replace(/&(#[xX][0-9a-fA-F]+;?|#\d+;?|[a-zA-Z][a-zA-Z0-9]*;)/g, (whole, ref) => {
    if (ref[0] === "#") {
      const digits = ref.replace(/;$/, "");
      const codePoint =
        digits[1] === "x" || digits[1] === "X" ? parseInt(digits.slice(2), 16) : parseInt(digits.slice(1), 10);
      if (Number.isNaN(codePoint)) return whole;
      try {
        return String.fromCodePoint(codePoint);
      } catch {
        return whole;
      }
    }
    const name = ref.slice(0, -1);
    return Object.prototype.hasOwnProperty.call(NAMED_ENTITIES, name) ? NAMED_ENTITIES[name] : whole;
  });
}

// وسمُ HTML قد يكون سطريّاً بحتاً (لا فراغَ يُنتجه العرضُ حين يُحذَف، كـ
// "<strong>"/"<em>"/"<span>"/"<a>") أو فاصلاً حقيقيّاً يُنتج سطراً أو فقرةً
// جديدةً عند العرض (كـ"<br>"، أو أيّ وسمٍ من مستوى الكتلة block-level كـ
// "<p>"/"<div>"/"<li>"). الأوّل يُسقَط بلا أثرٍ (فراغٍ): لا فراغَ منظوراً
// يفصله عمّا حوله فعلاً. الثاني يُستبدَل بمسافةٍ واحدة بدل الفراغ التامّ:
// "clinically<br>approved" يُعرَض على سطرَين منفصلَين فعليّاً — التصاقهما
// حرفيّاً في "clinicallyapproved" بعد إسقاط الوسم يُفلت الادّعاءَ (أو
// "api<br>key" البيانات الداخليّة) من الاكتشاف رغم انفصالهما البصريّ في
// الصفحة المعروضة (ملاحظة Codex). القائمةُ ليست كلَّ وسمٍ من مستوى الكتلة
// نظريّاً، بل الأشيَعُ فيما قد يظهر في نصٍّ يُحوَّل من Markdown كهذا.
const GAP_TAG_NAMES = new Set([
  "br", "p", "div", "li", "tr", "td", "th", "table", "thead", "tbody",
  "ul", "ol", "h1", "h2", "h3", "h4", "h5", "h6", "section", "article",
  "header", "footer", "blockquote", "hr", "dt", "dd", "pre",
]);
// تعليقُ HTML («<!-- ... -->») نصٌّ خاملٌ لا يعرضه المتصفّح إطلاقاً ولا
// يترك فراغاً منظوراً مكانه (بخلاف <br>)؛ نمطُ الوسم أدناه يشترط حرفاً بعد
// "<"/"</" فلا يطابق "<!--" أصلاً، فيبقى تعليقٌ كـ"clinically
// <!-- ملاحظة --> approved" فاصلاً حرفيّاً بين الكلمتين يُفلت المطابقةَ
// (ملاحظة Codex). يُسقَط بلا أثرٍ (فراغٍ) أسوةً بوسمٍ سطريٍّ — لكن فقط عند
// إعادة بناء النصّ *المعروض* فعليّاً (stripInlineHtml أدناه)؛ فحوصُ البيانات
// الحسّاسة تحتاج التعليقَ باقياً (محتواه منشورٌ في المصدر العامّ بصرف النظر
// عن العرض)، فتستخدم stripTags() وحدها بلا stripComments (راجع فحوصَ
// البيانات الشخصيّة/التفاصيل الداخليّة أدناه، وملاحظة Codex الثانية: بيانٌ
// حسّاسٌ داخل تعليقٍ يحتوي وسماً يقطعه، كـ"<!-- +49 <strong>151</strong>
// ... -->"، يفلت الفحصَ إن حُذف التعليقُ كاملاً أو إن بقي الوسمُ داخله).
function stripComments(text) {
  return text.replace(/<!--[\s\S]*?-->/g, "");
}
// فاصلُ سطرٍ إجباريٌّ بصيغة Markdown ("\" مباشرةً قبل فاصل سطرٍ) يُعرَض
// <br> فعليّاً (أسوةً بمسافتَين ختاميّتين قبل فاصل السطر، الصيغة الأخرى
// الأكثر شيوعاً وتُعالَج تلقائيّاً لاحقاً عبر طيّ \s+ العاديّ)، فيُستبدَل
// بمسافةٍ واحدة قبل مطابقة أنماط الوسم — وإلّا بقيت الـ"\" الحرفيّة حاجزاً
// بين الكلمتين رغم عرضهما منفصلتَين بسطرٍ فعليّاً (ملاحظة Codex).
function replaceHardBreaks(text) {
  return text.replace(/\\\r?\n/g, " ");
}
function stripTags(text) {
  return replaceHardBreaks(text).replace(
    /<\/?([a-zA-Z][a-zA-Z0-9]*)\b(?:"[^"]*"|'[^']*'|[^<>])*>/g,
    (whole, tagName) => (GAP_TAG_NAMES.has(tagName.toLowerCase()) ? " " : "")
  );
}
function stripInlineHtml(text) {
  return stripTags(stripComments(text));
}

