// بلا هذا، عبارةٌ كـ"معتمد **سريريّاً**" تبقى غيرَ مطابقةٍ لأنماط \s+ رغم أنّ
// الصفحة المعروضة تحمل الادّعاء فعلاً (ملاحظة Codex). ورابطُ Markdown
// "[نصّ](عنوان)" يُستبدَل بنصّه وحده (لا بالعنوان): عبارةٌ كـ"معتمد
// [سريريّاً](...)" تُعرَض "معتمد سريريّاً" فعليّاً، لا أن يبقى بين الكلمتَين
// قوسا نصٍّ وعنوانٌ يُفشلان مطابقة \s+ (ملاحظة Codex). ورابطُ Markdown
// بصيغة المرجع "[نصّ][معرّف]" (مع تعريفٍ منفصلٍ لاحقاً كـ"[معرّف]: عنوان")
// صيغةٌ قياسيّةٌ أخرى تُعرَض النصَّ نفسَه أيضاً، فتُسقَط بنفس المنطق (ملاحظة
// Codex). وأخيراً صيغةُ "المرجع المختصَر" ("[نصّ]" وحدها، حين يوجد تعريفٌ
// لهذا النصّ بعينه) تُعرَض نصَّها أيضاً بمعيار Markdown — بخلاف الصيغتَين
// أعلاه، هذه لا تُسقَط دائماً: قوسان حول نصٍّ عاديٍّ (لا رابط) شائعان في
// نثرٍ عاديٍّ (كتعليقٍ بين قوسين)، فتُقارَن فقط بمجموعة المعرّفات الموجودة
// فعلاً في الملفّ (سطرٌ بصيغة "[معرّف]: عنوان")، لا كلُّ "[نصّ]" حرفيّاً
// (ملاحظة Codex). دالّةٌ مشتركةٌ لا مكرّرةٌ في normalize() وحدها: فحوصُ
// البيانات الحسّاسة تحتاج حلَّ الروابط أيضاً — رقمٌ كـ"+49 [151](#)
// 23456789" يُعرَض رقماً عاديّاً فعليّاً (ملاحظة Codex). "!?" اختياريّةٌ في
// بداية كلّ نمطٍ: صورةُ Markdown ("![نصٌّ بديلٌ](عنوان)"/"![نصٌّ][معرّف]"/
// "![نصٌّ]") تتشارك الصياغةَ نفسَها مع الرابط العاديّ زائدةً "!" فقط، ونصُّها
// البديلُ يظهر فعليّاً لقارئات الشاشة وحين يتعذّر تحميل الصورة — فادّعاءٌ
// فيه ادّعاءٌ حقيقيٌّ يلزمه الإسقاطُ نفسُه (بلا معالجةٍ خاصّةٍ للصورة منفصلةً
// عن الرابط، فتشملها الصيغُ الثلاث كلّها تلقائيّاً — ملاحظتا Codex: الصيغةُ
// المضمّنة أوّلاً، ثمّ صيغةُ المرجع والمختصَر).
function resolveLinks(text) {
  const referenceLabels = new Set();
  const REFERENCE_DEFINITION_RE = /^[ \t]{0,3}\[([^\]]+)\]:\s*\S+/gm;
  let definitionMatch;
  while ((definitionMatch = REFERENCE_DEFINITION_RE.exec(text))) {
    referenceLabels.add(foldReferenceLabel(definitionMatch[1]));
  }
  return text
    .replace(/!?\[([^\]]*)\]\([^)]*\)/g, "$1")
    .replace(/!?\[([^\]]*)\]\[[^\]]*\]/g, "$1")
    .replace(/!?\[([^\]]*)\]/g, (whole, linkText) =>
      referenceLabels.has(foldReferenceLabel(linkText)) ? linkText : whole
    );
}

function normalize(rawInput) {
  const raw = decodeHtmlEntities(rawInput);
  const withoutDiacritics = raw.replace(DIACRITIC, "");
  const linksResolved = resolveLinks(withoutDiacritics).replace(/[*_~`]/g, "");
  // إسقاطُ وسم HTML مضمّنٍ، لا فقط ضمن أنماط CLAIM_PATTERNS: وسمٌ كـ
  // "<strong>" بين "api" و"key" يُفلت BANNED_SUBSTRINGS أيضاً (مطابَقةٌ
  // بـ.includes() الحرفيّة لا نمطاً)، فوضعُ الإسقاط هنا يشمل كلَّ فحصٍ لاحقٍ
  // معاً بدل تكرار التحمّل في كلّ نمطٍ. stripInlineHtml() (أعلاه) تُفرّق بين
  // وسمٍ سطريٍّ بحتٍ (يُسقَط بلا أثرٍ) ووسمٍ فاصلٍ حقيقيٍّ (يُستبدَل بمسافة).
  return stripInlineHtml(linksResolved)
    .replace(/\s+/g, " ")
    .toLowerCase();
}

